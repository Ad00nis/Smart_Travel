import React, { useState } from "react";
import { Download, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import jsPDF from "jspdf";

export default function ExportButton({ tripTitle, destination, days }) {
  const [exporting, setExporting] = useState(false);

  const handleExport = async () => {
    setExporting(true);

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    let y = 20;

    // Title
    doc.setFontSize(22);
    doc.setFont("helvetica", "bold");
    doc.text(tripTitle || "My Trip", 20, y);
    y += 10;

    // Destination info
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(100, 100, 100);
    doc.text(`${destination.name}, ${destination.country}  ·  ${destination.category}  ·  £${destination.daily_cost}/day`, 20, y);
    y += 6;
    doc.text(`Best season: ${destination.best_season || "N/A"}  ·  Safety: ${destination.safety_rating}/10`, 20, y);
    y += 12;

    // Divider
    doc.setDrawColor(200, 200, 200);
    doc.line(20, y, pageWidth - 20, y);
    y += 10;

    // Days
    days.forEach((day, index) => {
      // Check if we need a new page
      if (y > 260) {
        doc.addPage();
        y = 20;
      }

      // Day header
      doc.setFontSize(14);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(16, 185, 129); // emerald
      doc.text(day.label, 20, y);
      y += 8;

      // Activities
      doc.setFontSize(11);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(50, 50, 50);

      if (day.activities.length === 0) {
        doc.setTextColor(150, 150, 150);
        doc.text("No activities planned", 25, y);
        y += 7;
      } else {
        day.activities.forEach((activity) => {
          if (y > 270) {
            doc.addPage();
            y = 20;
          }
          const timeStr = activity.time ? `${activity.time}  ` : "";
          doc.setTextColor(120, 120, 120);
          doc.text("•", 25, y);
          doc.setTextColor(50, 50, 50);
          doc.text(`${timeStr}${activity.text}`, 32, y);
          y += 7;
        });
      }

      y += 6;

      // Divider between days
      if (index < days.length - 1) {
        doc.setDrawColor(230, 230, 230);
        doc.line(20, y, pageWidth - 20, y);
        y += 8;
      }
    });

    // Footer
    const totalDays = days.length;
    const totalActivities = days.reduce((acc, d) => acc + d.activities.length, 0);
    const estCost = destination.daily_cost * totalDays;

    if (y > 250) { doc.addPage(); y = 20; }
    y += 6;
    doc.setDrawColor(200, 200, 200);
    doc.line(20, y, pageWidth - 20, y);
    y += 10;
    doc.setFontSize(10);
    doc.setTextColor(120, 120, 120);
    doc.text(`${totalDays} days  ·  ${totalActivities} activities  ·  Est. cost £${estCost.toLocaleString()}`, 20, y);
    y += 6;
    doc.text(`Generated by Smart Planner`, 20, y);

    doc.save(`${tripTitle || "itinerary"}.pdf`);
    setExporting(false);
  };

  return (
    <Button
      onClick={handleExport}
      disabled={exporting || days.length === 0}
      variant="outline"
      className="border-emerald-200 text-emerald-700 hover:bg-emerald-50"
    >
      {exporting ? (
        <><Loader2 className="w-4 h-4 mr-2 animate-spin" />Exporting...</>
      ) : (
        <><Download className="w-4 h-4 mr-2" />Export PDF</>
      )}
    </Button>
  );
}